#!/usr/bin/env node
import { writeFileSync, readFileSync } from 'node:fs'
import { execSync } from 'node:child_process'

const [cmd, ...rest] = process.argv.slice(2)

const flags = {}
const args = []
for (let i = 0; i < rest.length; i++) {
  if (rest[i].startsWith('--')) flags[rest[i].slice(2)] = rest[i + 1]?.startsWith('--') ? true : rest[++i]
  else if (rest[i] === '-o') flags.out = rest[++i]
  else args.push(rest[i])
}

const url = (flags.url ?? process.env.MANIFOLD_URL ?? 'http://localhost:8000').replace(/\/+$/, '')
const token = flags.token ?? process.env.MANIFOLD_TOKEN

async function api(method, path, body) {
  const res = await fetch(`${url}/api/manifold/${path}`, {
    method,
    headers: {
      Accept: 'application/json',
      ...(body ? { 'Content-Type': 'application/json' } : {}),
      ...(token ? { Authorization: `Bearer ${token}` } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  })
  const json = res.status === 204 ? null : await res.json().catch(() => null)
  if (!res.ok) throw new Error(`${method} /${path} -> ${res.status}: ${json?.message ?? 'request failed'}`)
  return json
}

const TS_TYPES = {
  text: 'string', slug: 'string', email: 'string', textarea: 'string',
  richtext: 'string', datetime: 'string', number: 'number', boolean: 'boolean',
  relationship: 'number',
}

function pascal(slug) {
  return slug.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())
}

async function typesCommand() {
  const { collections } = await api('GET', 'schema')
  let out = `// Generated by \`manifold types\` from ${url} — do not edit by hand.\n\n`

  for (const col of collections) {
    out += `export interface ${pascal(col.slug)} {\n  id: number\n`
    for (const f of col.fields) {
      const ts = f.type === 'select'
        ? Object.keys(f.options ?? {}).map((o) => JSON.stringify(o)).join(' | ') || 'string'
        : TS_TYPES[f.type] ?? 'unknown'
      out += `  ${f.column}: ${ts}${f.required ? '' : ' | null'}\n`
    }
    out += `  created_at: string\n  updated_at: string\n}\n\n`
  }

  out += `export interface ManifoldCollections {\n`
  for (const col of collections) out += `  ${JSON.stringify(col.slug)}: ${pascal(col.slug)}\n`
  out += `}\n`

  const file = flags.out ?? 'manifold-types.d.ts'
  writeFileSync(file, out)
  console.log(`Wrote ${collections.length} collection interfaces to ${file}`)
}

async function exportCommand() {
  const [slug] = args
  if (!slug) fail('Usage: manifold export <collection> [--url ...] [--token ...] [-o file.json]')

  const rows = []
  for (let page = 1, last = 1; page <= last; page++) {
    const res = await api('GET', `${slug}?page=${page}&perPage=100`)
    rows.push(...res.data)
    last = res.meta.lastPage
  }

  const json = JSON.stringify(rows, null, 2)
  if (flags.out) {
    writeFileSync(flags.out, json)
    console.log(`Exported ${rows.length} entries to ${flags.out}`)
  } else {
    console.log(json)
  }
}

async function importCommand() {
  const [slug, file] = args
  if (!slug || !file) fail('Usage: manifold import <collection> <file.json> --token ... [--url ...]')

  const rows = JSON.parse(readFileSync(file, 'utf8'))
  let ok = 0
  for (const { id, created_at, updated_at, ...data } of rows) {
    await api('POST', slug, data)
    ok++
  }
  console.log(`Imported ${ok}/${rows.length} entries into ${slug}`)
}

function initCommand() {
  const [dir] = args
  if (!dir) fail('Usage: manifold init <directory>')
  const repo = flags.repo ?? 'https://github.com/multidevagency/manifold.git'
  execSync(`git clone ${repo} ${JSON.stringify(dir)}`, { stdio: 'inherit' })
  console.log(`\nNext steps:\n  cd ${dir}\n  composer install && cp .env.example .env && php artisan key:generate\n  php artisan migrate --seed\n  cd admin && pnpm install && cd ..\n  composer dev`)
}

function fail(msg) {
  console.error(msg)
  process.exit(1)
}

const commands = { types: typesCommand, export: exportCommand, import: importCommand, init: initCommand }

if (!commands[cmd]) {
  console.log(`manifold — CLI for Manifold CMS

Usage:
  manifold types   [--url URL] [--token TOKEN] [-o manifold-types.d.ts]
  manifold export  <collection> [--url URL] [--token TOKEN] [-o file.json]
  manifold import  <collection> <file.json> --token TOKEN [--url URL]
  manifold init    <directory> [--repo GIT_URL]

--url defaults to $MANIFOLD_URL or http://localhost:8000; --token to $MANIFOLD_TOKEN.`)
  process.exit(cmd ? 1 : 0)
}

commands[cmd]().catch((e) => fail(e.message))
